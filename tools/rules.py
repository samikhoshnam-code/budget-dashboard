# قواعد دسته‌بندی ثابت؛ ترتیب قواعد مهم است. اصلاح قاعده = ویرایش همین فایل.
import re
C1='حقوق و پرسنلی (مساعده، وام، بیماری و سایر)'
C2='بیمه و مالیات'
C3='صندوق پس انداز و سایر کسورات'
C4='سنوات و ۴٪ بازنشستگان و طبقه بندی مشاغل'
C5='پیمان'
C6='قبوض و سایر'
C7='بیمه تکمیلی، مسئولیت'
C8='بن کارگری'
C9='خرید'
C10='بودجه مدیریت'
CATS=[C1,C2,C3,C4,C5,C6,C7,C8,C9,C10]
TR='انتقال بین بانکی (خارج از گزارش)'
U='قاعده شما'; A='تشخیص خودکار'; Q='نیاز به تایید'

def classify(d,cp):
    d=(d or '').strip(); cp=(cp or '').strip()
    if 'انتقالی بانک به بانک' in d: return TR,A,'انتقال بانک به بانک','واریز/انتقال بین حساب‌ها؛ هزینه نیست'
    if 'انتقالی به تنخواه' in d: return C9,U,'انتقالی به تنخواه','قاعده شما: انتقالی به تنخواه ← خرید'
    if 'انتقال به صندوق' in d: return C10,U,'انتقال به صندوق','قاعده شما: انتقال به صندوق ← بودجه مدیریت'
    if cp=='دفتر مدیریت': return C1,A,'هزینه سفر و ماموریت (دفتر مدیریت)','هزینه دفتر مدیریت ← ردیف بودجه مدیریت'
    if 'استرداد سپرده' in d: return C5,U,'استرداد سپرده','قاعده شما: استرداد سپرده ← پیمان'
    if 'صورت وضعیت' in d: return C5,U,'صورت وضعیت','قاعده شما: صورت وضعیت ← پیمان'
    if 'کارت رفاهی' in d: return C9,A,'شارژ کارت رفاهی','کارت رفاهی غیرنقدی = بن کارگری (۳۵ میلیارد در بودجه)'
    if 'وام نوبتی پس انداز' in d: return C3,A,'وام نوبتی صندوق پس انداز','صندوق پس انداز کارکنان'
    if 'خرید آب' in d: return C9,U,'خرید آب','قاعده شما: خرید ← خرید (تایید شد)'
    if 'نوشت افزار' in d: return C1,U,'خرید پرسنل از نوشت‌افزار (اقساطی)','قاعده شما: نوشت‌افزار پرسنل ← صندوق پس انداز و سایر کسورات'
    if 'خرید' in d: return C9,U,'خرید کالا (شامل پ پ)','قاعده شما: هرجا خرید بود ← خرید'
    if d.startswith('پ پ'): return C9,Q,'پیش‌پرداخت (پ پ) بدون کلمه خرید','پ پ = پیش‌پرداخت خرید فرض شد'
    if 'سنوات' in d: return C4,A,'تسویه سنوات خدمت','هم‌نام ردیف ۴'
    if 'طبقه بندی مشاغل' in d: return C4,A,'مطالبات/دادرسی طبقه‌بندی مشاغل','هم‌نام ردیف ۴'
    if 'معاینات بازنشستگی' in d: return C4,Q,'معاینات بازنشستگی','به‌دلیل «بازنشستگان» در نام ردیف ۴'
    if 'سخت و زیان آور' in d: return C4,U,'۴٪ سخت و زیان‌آور','قاعده شما: ۴٪ سخت و زیان‌آور ← ردیف سنوات و ۴٪ بازنشستگان'
    if 'اقساط پرداخت نشده' in d: return C1,U,'اقساط پرداخت‌نشده بیمه شخص ثالث','قاعده شما: اقساط پرداخت نشده ← پرسنلی'
    if 'اجرای ثبت' in d: return C1,U,'اجرای ثبت','قاعده شما: اجرای ثبت ← پرسنلی'
    if 'مساعده' in d: return C1,U,'مساعده','قاعده شما: مساعده ← پرسنلی'
    if 'وام' in d: return C1,U,'وام ضروری','قاعده شما: وام ← پرسنلی'
    if 'برگشت علی الحساب' in d: return C1,A,'برگشت علی‌الحساب (ستون بدهکار؛ در محاسبه نیست)','فقط ستون بستانکار محاسبه می‌شود'
    if 'علی الحساب' in d: return C1,A,'علی‌الحساب درمان','درمان/بیماری ← پرسنلی'
    if 'درمان' in d: return C1,A,'هزینه درمان و بهداشت','بیماری ← پرسنلی'
    if 'ازدواج' in d or 'پاداش' in d: return C1,A,'پاداش / کمک هزینه ازدواج','پرسنلی'
    if 'بیمه تکمیلی' in d or 'بیمه مسئولیت' in d or 'بیمه آتش' in d or 'شکست ماشین' in d:
        return C7,A,'اقساط بیمه تکمیلی/مسئولیت/آتش‌سوزی/شکست ماشین‌آلات','هم‌نام ردیف ۷ و نامه بودجه'
    if 'حسابرسی بیمه' in d: return C2,A,'بدهی حسابرسی بیمه (تامین اجتماعی)','بیمه'
    if 'بیمه حقوق' in d: return C2,A,'بیمه حقوق (تامین اجتماعی)','بیمه'
    if 'مالیت حقوق' in d or 'مالیات' in d: return C2,A,'مالیات (حقوق/ارزش افزوده/خدمات)','مالیات'
    if re.search(r'حقوق',d): return C1,A,'حقوق ماهانه و مابه‌التفاوت','حقوق ← پرسنلی'
    if 'برق' in d or 'گاز مصرفی' in d or 'آب مصرفی' in d: return C6,U,'قبوض برق/آب/گاز','قاعده شما: قبوض ← قبوض و سایر'
    if 'کمیسیون ماده 100' in d: return C6,Q,'کمیسیون ماده ۱۰۰ شهرداری','سایر؛ ماهیت جریمه/عوارض'
    if 'هاستینگ' in d: return C5,U,'هاستینگ','انتخاب شما: پیمان'
    if 'کارمزد تعویض' in d: return C10,U,'کارمزد تعویض اسکناس','انتخاب شما: بودجه مدیریت'
    if 'مشاوره اداری' in d and 'طبقه بندی' in cp: return C1,U,'مشاوره طبقه‌بندی مشاغل','انتخاب شما: پرسنلی'
    if any(k in d for k in ['هاستینگ','مشاوره اداری','صورتجلسات','کارمزد تعویض']):
        return C6,A,'خدمات و هزینه‌های متفرقه (هاستینگ، مشاوره، ثبت، کارمزد)','سایر'
    if any(k in d for k in ['اسیدشویی','تعمیر','شارژ کپسول','سنگ زنی','سیم پیچی','ساخت','پرس سیم']):
        return C9,U,'خدمات/تعمیرات عملیاتی','قاعده شما: تعمیرات و خدمات بدون کلمه خرید ← خرید (تایید شد)'
    if d=='' and cp=='امور مالی و اقتصادی': return C5,U,'پرداخت بدون شرح (امور مالی)','انتخاب شما: پیمان'
    return 'طبقه بندی نشده',Q,'نامشخص','هیچ قاعده‌ای پیدا نشد'

